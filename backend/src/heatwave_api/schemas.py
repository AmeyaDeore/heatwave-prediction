"""Request and response contracts for /api/v1 (documented in docs/api/README.md).

The risk-class vocabulary is spelled once, as `RiskClass`, and checked against
config/risk_classes.yaml at startup (app.py), so a drift fails the build, not a request.
"""

from datetime import date, datetime
from typing import Annotated, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

RiskClass = Literal["NORMAL", "HEATWAVE", "SEVERE_HEATWAVE"]
AlertSeverity = Literal["HEATWAVE", "SEVERE_HEATWAVE"]  # there is nothing to warn about at NORMAL
AlertStatus = Literal["DRAFT", "READY", "ISSUED"]
DeliveryStatus = Literal["READY", "NOTIFIED", "PENDING", "FAILED"]

RegionId = Annotated[str, StringConstraints(pattern=r"^[a-z][a-z0-9_]{1,40}$")]


class Strict(BaseModel):
    """Request bodies reject unknown fields: a typo is an error, never a silent default."""

    model_config = ConfigDict(extra="forbid")


# -- regions and weather --------------------------------------------------------------


class RegionOut(BaseModel):
    id: str
    name: str
    district: str
    state: str
    zone: str
    lat: float
    lon: float


class WeatherProvenance(BaseModel):
    source: str
    issued_at: datetime
    age_hours: float
    stale: bool  # older than WEATHER_STALE_AFTER_HOURS: served, but the UI should say so


class WeatherOut(BaseModel):
    region: RegionOut
    date: date
    lead_days: int
    tmax_c: float | None
    normal_tmax_c: float | None
    temp_deviation_c: float | None
    rh_pct: float | None
    wind_ms: float | None
    solar_mj_m2: float | None
    precip_mm: float | None
    provenance: WeatherProvenance


# -- prediction -----------------------------------------------------------------------


class PredictRequest(Strict):
    region_id: RegionId
    lead_days: int = Field(0, ge=0, le=3, description="0 = today, 1-3 = the next three days")


class ForecastWindow(BaseModel):
    valid_date: date
    lead_days: int
    issued_at: datetime
    horizon_days: int = 3


class FactorOut(BaseModel):
    rank: int
    feature: str
    label: str
    unit: str
    value: float
    display_value: str
    imputed: bool
    contribution: float
    share_pct: float
    direction: Literal["increases_risk", "decreases_risk", "neutral"]


class ExplanationOut(BaseModel):
    target_class: RiskClass
    reference_class: RiskClass
    quantity: str
    explained: str
    baseline: float
    output: float
    factors: list[FactorOut]
    summary: str
    model_version: str
    explainer_id: str


class PredictionOut(BaseModel):
    prediction_id: str
    created_at: datetime
    region: RegionOut
    forecast_window: ForecastWindow
    risk_class: RiskClass
    confidence: float
    probabilities: dict[RiskClass, float]
    inputs: dict[str, float | None]  # the values the model was given, before imputation
    explanation: ExplanationOut
    recommended_actions: list[str]
    actions_version: str
    weather: WeatherProvenance


# -- alerts ---------------------------------------------------------------------------


class AlertBase(Strict):
    severity: AlertSeverity
    message: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=10, max_length=1000)
    ]
    channels: list[str] = Field(min_length=1, max_length=20)


class AlertCreate(AlertBase):
    client_request_id: UUID = Field(
        description="Generated by the client once per form; a replay returns the same alert."
    )
    region_id: RegionId
    status: Literal["DRAFT", "READY", "ISSUED"] = "DRAFT"
    prediction_id: str | None = None


class AlertUpdate(Strict):
    """Edit a DRAFT/READY alert and/or move it along DRAFT → READY → ISSUED."""

    severity: AlertSeverity | None = None
    message: (
        Annotated[str, StringConstraints(strip_whitespace=True, min_length=10, max_length=1000)]
        | None
    ) = None
    channels: list[str] | None = Field(None, min_length=1, max_length=20)
    status: AlertStatus | None = None


class ChannelDelivery(BaseModel):
    channel: str
    label: str
    status: DeliveryStatus
    detail: str | None = None  # why a delivery FAILED
    updated_at: datetime


class DeliverySummary(BaseModel):
    total: int
    notified: int
    failed: int
    pending: int
    all_delivered: bool


class AlertOut(BaseModel):
    alert_id: str
    status: AlertStatus
    severity: AlertSeverity
    region: RegionOut
    message: str
    prediction_id: str | None
    channels: list[ChannelDelivery]
    delivery_summary: DeliverySummary
    created_at: datetime
    created_by: str
    issued_at: datetime | None
    updated_at: datetime
    idempotent_replay: bool = False


class AlertList(BaseModel):
    alerts: list[AlertOut]
    total: int
    limit: int
    offset: int


class ChannelOut(BaseModel):
    id: str
    label: str
    mechanism: Literal["sms", "email", "in_app"]  # Part 09 delivery mechanism


class AdvisoryOut(BaseModel):
    """A published public advisory: what the portal and display boards show (Part 09)."""

    alert_id: str
    channel: str
    region_id: str
    severity: AlertSeverity
    title: str
    body: str
    published_at: datetime


class NotificationAttemptOut(BaseModel):
    """One dispatch attempt from the audit trail (Part 09 §6)."""

    channel: str
    mechanism: str
    provider: str
    recipient: str | None
    attempt: int
    outcome: Literal["SUCCESS", "TRANSIENT_FAILURE", "PERMANENT_FAILURE"]
    detail: str | None
    provider_ref: str | None
    started_at: datetime
    duration_ms: int


# -- analytics ------------------------------------------------------------------------


class TrendPoint(BaseModel):
    date: date
    avg_tmax_c: float
    max_tmax_c: float
    predictions: int


class MonthlyCount(BaseModel):
    month: str  # YYYY-MM
    heatwave_events: int
    severe_events: int


class ModelPerformance(BaseModel):
    model_version: str
    model_family: str
    explainer_id: str
    labeling_rule_version: str
    evaluated_on: str
    test_rows: int
    accuracy: float
    precision_macro: float
    recall_macro: float
    f1_macro: float
    per_class: dict[str, dict[str, float]]
    mean_confidence: float
    calibration_ece: float


class AnalyticsOut(BaseModel):
    period_days: int
    region_id: str | None
    data_source: Literal["stored_predictions"]
    temperature_trend: list[TrendPoint]
    events_per_month: list[MonthlyCount]
    risk_distribution: dict[RiskClass, int]
    predictions_in_period: int
    model_performance: ModelPerformance


# -- auth and health ------------------------------------------------------------------


class LoginRequest(Strict):
    username: Annotated[str, StringConstraints(min_length=1, max_length=64)]
    password: Annotated[str, StringConstraints(min_length=1, max_length=256)]


class UserOut(BaseModel):
    id: str
    username: str
    display_name: str
    role: str


class TokenOut(BaseModel):
    access_token: str
    token_type: Literal["bearer"] = "bearer"
    expires_at: datetime
    user: UserOut


class ReadinessOut(BaseModel):
    ready: bool
    model_version: str
    explainer_id: str
    weather_data: Literal["ok", "stale", "unavailable"]
    weather_issued_at: datetime | None
